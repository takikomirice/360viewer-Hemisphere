const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'scripts/progressive-images/google-client.js'),'utf8');
const output=path.join(root,'progressive-client.html');
const expected='<!-- Generated by scripts/sync-progressive-client.js -->\n<script>\n'+source+'\n</script>\n';
if(process.argv.includes('--check')) {if(!fs.existsSync(output)||fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n')!==expected.replace(/\r\n/g,'\n'))throw Error('Progressive client is stale');}
else fs.writeFileSync(output,expected);
